static void SM16206_SetBit(uint16_t *buffer, uint8_t seg, uint16_t bits, uint8_t state){
	if (state == 1) 
	{
		buffer[seg] |= bits;   
	} 
	else 
	{
		buffer[seg] &= ~bits;  
	}
}

void SM16206_Write(uint16_t *buffer, uint8_t size){
	uint8_t i, j;
	uint16_t data;

	// DS_OE_L;   

	for(i = size; i > 0; i--)   
	{
    data = buffer[i - 1]; 

		for(j = 0; j < 16; j++)
		{
			if(data & 0x8000) // Bit MSB 
			{
				DS_SDI_H;
			}
			else
			{
				DS_SDI_L;
			}

			DS_SCLK_H;             
			DS_SCLK_L;

			data <<= 1;            
		}
	}

	DS_LE_H;   
	DS_LE_L;
}

