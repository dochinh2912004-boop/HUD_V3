void HUD_SetDisplayMask(uint16_t mask)
{
    hud_display_mask = mask;
    
}

// Ghi Flash — chỉ dùng khi web config save
void HUD_SaveDisplayMask(uint16_t mask)
{
    HUD_SetDisplayMask(mask);
    Flash_Write_uint8_t(KEY_DISPLAY_REGION_MASK_LO, (uint8_t)(hud_display_mask & 0xFF));
    Flash_Write_uint8_t(KEY_DISPLAY_REGION_MASK_HI, (uint8_t)((hud_display_mask >> 8) & 0xFF));
    ESP_LOGI("HUD_MASK", "Da ghi flash mask=0x%04X", hud_display_mask);
}

uint16_t HUD_GetDisplayMask(void)
{
	return hud_display_mask;
}

