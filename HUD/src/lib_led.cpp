	if( carmodel_count == FADIL 
		||carmodel_count == ECVAN 
		||carmodel_count == LYNKCO1 
		||carmodel_count == MINIO 
		||carmodel_count == MAZDA3_2018
		||carmodel_count == MAZDA3_2021
		||carmodel_count == MAZDACX5
		||carmodel_count == Ford_XLS_2019
	  ||carmodel_count == Huyndai_Creta)
	{
		display_partition_time = 0;
	}	
	/* Tat %pin */
	if( carmodel_count == LYNKCO6 
		||carmodel_count == FADIL 
		||carmodel_count == LYNKCO1 
		||carmodel_count == MAZDA3_2018
		||carmodel_count == MAZDA3_2021
		||carmodel_count == MAZDACX5
		||carmodel_count == Ford_XLS_2019
	    ||carmodel_count == Huyndai_Creta)
	{
		display_partition_battery = 0;
	}
